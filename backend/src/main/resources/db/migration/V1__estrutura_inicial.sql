CREATE TABLE setores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em TIMESTAMPTZ NOT NULL, atualizado_em TIMESTAMPTZ NOT NULL
);
CREATE TABLE categorias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL, descricao VARCHAR(500), ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em TIMESTAMPTZ NOT NULL, atualizado_em TIMESTAMPTZ NOT NULL
);
CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(120) NOT NULL, email VARCHAR(200) NOT NULL UNIQUE, senha_hash VARCHAR(255) NOT NULL,
 perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('SOLICITANTE','TECNICO','ADMIN')),
 setor_id BIGINT NOT NULL REFERENCES setores(id), ativo BOOLEAN NOT NULL DEFAULT TRUE,
 troca_senha_obrigatoria BOOLEAN NOT NULL DEFAULT TRUE, auth_version BIGINT NOT NULL DEFAULT 0,
 criado_em TIMESTAMPTZ NOT NULL, atualizado_em TIMESTAMPTZ NOT NULL,
 CONSTRAINT email_normalizado CHECK (email = lower(trim(email)))
);
CREATE TABLE chamados (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(150) NOT NULL, descricao VARCHAR(5000) NOT NULL,
 impacto VARCHAR(30) NOT NULL CHECK (impacto IN ('INDIVIDUAL','SETOR','ORGANIZACAO')),
 status VARCHAR(30) NOT NULL CHECK (status IN ('ABERTO','EM_ATENDIMENTO','AGUARDANDO_USUARIO','RESOLVIDO','FECHADO','CANCELADO')),
 prioridade VARCHAR(20) NOT NULL CHECK (prioridade IN ('BAIXA','MEDIA','ALTA','CRITICA')),
 solicitante_id BIGINT NOT NULL REFERENCES usuarios(id), setor_origem_id BIGINT NOT NULL REFERENCES setores(id),
 responsavel_id BIGINT REFERENCES usuarios(id), categoria_id BIGINT NOT NULL REFERENCES categorias(id),
 solucao VARCHAR(5000), criado_em TIMESTAMPTZ NOT NULL, atualizado_em TIMESTAMPTZ NOT NULL,
 resolvido_em TIMESTAMPTZ, fechado_em TIMESTAMPTZ, cancelado_em TIMESTAMPTZ, versao BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT estado_responsavel CHECK (status NOT IN ('EM_ATENDIMENTO','AGUARDANDO_USUARIO','RESOLVIDO','FECHADO') OR responsavel_id IS NOT NULL),
 CONSTRAINT resolucao_obrigatoria CHECK (status NOT IN ('RESOLVIDO','FECHADO') OR solucao IS NOT NULL)
);
CREATE TABLE comentarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chamado_id BIGINT NOT NULL REFERENCES chamados(id), autor_id BIGINT NOT NULL REFERENCES usuarios(id),
 conteudo VARCHAR(5000) NOT NULL, visibilidade VARCHAR(10) NOT NULL CHECK (visibilidade IN ('PUBLICO','INTERNO')),
 criado_em TIMESTAMPTZ NOT NULL
);
CREATE TABLE historico (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 chamado_id BIGINT NOT NULL REFERENCES chamados(id), autor_id BIGINT NOT NULL REFERENCES usuarios(id),
 tipo_evento VARCHAR(20) NOT NULL CHECK (tipo_evento IN ('ABERTURA','STATUS','RESPONSAVEL','PRIORIDADE','CATEGORIA')),
 valor_anterior VARCHAR(200), valor_novo VARCHAR(200), justificativa VARCHAR(5000), criado_em TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_usuario_setor ON usuarios(setor_id);
CREATE INDEX idx_chamado_solicitante_data ON chamados(solicitante_id, criado_em DESC);
CREATE INDEX idx_chamado_responsavel_status ON chamados(responsavel_id, status);
CREATE INDEX idx_chamado_status_data ON chamados(status, criado_em DESC);
CREATE INDEX idx_chamado_setor ON chamados(setor_origem_id);
CREATE INDEX idx_chamado_categoria ON chamados(categoria_id);
CREATE INDEX idx_comentario_chamado_data ON comentarios(chamado_id, criado_em, id);
CREATE INDEX idx_historico_chamado_data ON historico(chamado_id, criado_em, id);
